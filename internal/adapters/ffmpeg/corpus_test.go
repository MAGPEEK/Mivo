package ffmpeg_test

import (
	"encoding/json"
	"errors"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// corpusDirectory is the generated test corpus seen from this package directory (ADR 0021).
const corpusDirectory = "../../../testdata/media"

// manifestSchemaVersion is the corpus manifest version this test understands.
const manifestSchemaVersion = 2

const statusGenerated = "generated"

// corpusManifest holds the fields of testdata/media/manifest.json this package checks.
// scripts/gen-testmedia is package main and cannot be imported, so the shape is repeated.
type corpusManifest struct {
	SchemaVersion int          `json:"schemaVersion"`
	FFmpegVersion string       `json:"ffmpegVersion"`
	Cases         []corpusCase `json:"cases"`
}

type corpusCase struct {
	Name     string            `json:"name"`
	Category string            `json:"category"`
	File     string            `json:"file"`
	Status   string            `json:"status"`
	Expected corpusExpectation `json:"expected"`
}

type corpusExpectation struct {
	Container       string               `json:"container"`
	ProbeFormat     string               `json:"probeFormat"`
	DurationSeconds float64              `json:"durationSeconds"`
	Video           *videoExpectation    `json:"video"`
	Audio           []audioExpectation   `json:"audio"`
	Subtitles       []trackedCodec       `json:"subtitles"`
	Sidecars        []sidecarExpectation `json:"sidecars"`
}

type videoExpectation struct {
	Codec          string            `json:"codec"`
	Profile        string            `json:"profile"`
	CodecTag       string            `json:"codecTag"`
	PixelFormat    string            `json:"pixelFormat"`
	ColorPrimaries string            `json:"colorPrimaries"`
	ColorTransfer  string            `json:"colorTransfer"`
	ColorSpace     string            `json:"colorSpace"`
	HDR            string            `json:"hdr"`
	Width          int               `json:"width"`
	Height         int               `json:"height"`
	Track          *trackExpectation `json:"track"`
}

type audioExpectation struct {
	Codec      string            `json:"codec"`
	SampleRate int               `json:"sampleRate"`
	Channels   int               `json:"channels"`
	BitDepth   int               `json:"bitDepth"`
	Track      *trackExpectation `json:"track"`
}

type trackedCodec struct {
	Codec string            `json:"codec"`
	Track *trackExpectation `json:"track"`
}

type trackExpectation struct {
	Language string `json:"language"`
	Default  bool   `json:"default"`
	Forced   bool   `json:"forced"`
}

type sidecarExpectation struct {
	File        string `json:"file"`
	ProbeFormat string `json:"probeFormat"`
	Codec       string `json:"codec"`
}

// requireFFprobe returns the ffprobe path or skips the test with the reason.
func requireFFprobe(t *testing.T) string {
	t.Helper()

	if testing.Short() {
		t.Skip("skipping FFmpeg integration test in -short mode")
	}

	ffprobePath, err := exec.LookPath("ffprobe")
	if err != nil {
		t.Skip("skipping FFmpeg integration test: ffprobe is not on PATH " +
			"(install FFmpeg, see docs/development.md)")
	}

	return ffprobePath
}

// requireCorpus returns the ffprobe path and the corpus manifest, or skips the test with
// the reason.
func requireCorpus(t *testing.T) (string, corpusManifest) {
	t.Helper()

	ffprobePath := requireFFprobe(t)

	data, err := os.ReadFile(filepath.Join(corpusDirectory, "manifest.json"))
	if errors.Is(err, fs.ErrNotExist) {
		t.Skip("skipping FFmpeg corpus integration test: testdata/media/manifest.json is missing " +
			"(generate it with `go run ./scripts/gen-testmedia`)")
	}

	if err != nil {
		t.Fatalf("read corpus manifest: %v", err)
	}

	var manifest corpusManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatalf("decode corpus manifest: %v", err)
	}

	if manifest.SchemaVersion != manifestSchemaVersion {
		t.Fatalf("corpus manifest has schema version %d, want %d; regenerate the corpus",
			manifest.SchemaVersion, manifestSchemaVersion)
	}

	return ffprobePath, manifest
}

// corpusPath returns the absolute path of a manifest file entry.
func corpusPath(t *testing.T, slashPath string) string {
	t.Helper()

	path, err := filepath.Abs(filepath.Join(corpusDirectory, filepath.FromSlash(slashPath)))
	if err != nil {
		t.Fatalf("absolute corpus path: %v", err)
	}

	return path
}

// corpusCaseByName returns a generated case or skips when the corpus lacks it.
func corpusCaseByName(t *testing.T, manifest corpusManifest, name string) corpusCase {
	t.Helper()

	for _, entry := range manifest.Cases {
		if entry.Name == name && entry.Status == statusGenerated {
			return entry
		}
	}

	t.Skipf("corpus case %s was not generated by the local FFmpeg", name)

	return corpusCase{}
}

// copyFile copies a corpus file into directory under a new name and returns its path.
func copyFile(t *testing.T, source, directory, name string) string {
	t.Helper()

	data, err := os.ReadFile(source) //nolint:gosec // corpus path built by the test
	if err != nil {
		t.Fatalf("read %s: %v", source, err)
	}

	root, err := os.OpenRoot(directory)
	if err != nil {
		t.Fatalf("open %s: %v", directory, err)
	}
	writeErr := root.WriteFile(name, data, 0o600)
	if err := errors.Join(writeErr, root.Close()); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}

	return filepath.Join(directory, name)
}
