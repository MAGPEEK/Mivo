#!/bin/sh
# build-ffmpeg.sh - configure and build static ffmpeg and ffprobe for one family.
#
#   build-ffmpeg.sh <family> <ffmpeg-sources> <prefix> <dest>
#
# <ffmpeg-sources> holds the verified FFmpeg tarball and versions.env; <prefix> the libraries of
# build-libs.sh. Writes <dest>/ffmpeg, <dest>/ffprobe (stripped) and <dest>/configuration.txt
# (the configure line FFmpeg embeds). The cross toolchain must be on PATH.
#
# The configuration is GPL version 3 (--enable-gpl --enable-version3) with libx264 and FFmpeg's
# native AAC encoder. It never contains --enable-nonfree or libfdk-aac (ADR 0015 Notes, ADR 0026
# Notes); the script refuses to build if either appears.
#
# Environment: JOBS (parallel make jobs, default: number of CPUs).
# shellcheck source-path=SCRIPTDIR
set -eu

[ "$#" -eq 4 ] || {
	printf 'usage: %s <family> <ffmpeg-sources> <prefix> <dest>\n' "$0" >&2
	exit 2
}
family=$1
sources=$2
prefix=$3
dest=$4
script_dir=$(dirname "$0")

# shellcheck source=families.sh
. "$script_dir/families.sh"
# shellcheck source=layout.sh
. "$script_dir/layout.sh"
# shellcheck source=compile-flags.sh
. "$script_dir/compile-flags.sh"
# shellcheck source=recipe.sh
. "$script_dir/recipe.sh"
load_family "$family"
# shellcheck disable=SC1091 # generated by fetch-sources.sh verify
. "$sources/versions.env"

jobs=${JOBS:-$(nproc)}
work="$BUILD_ROOT/ffmpeg"

# Input demuxers: exactly the single-file demuxers of the server's -format_whitelist
# (allowedDemuxers and image2 in internal/adapters/ffmpeg/probe.go, ADR 0022 Notes M2-24b),
# by configure name: "mpeg" is mpegps, "<x>_pipe" is image_<x>_pipe. Playlist and reference
# demuxers (concat, hls, dash, imf, vobsub) are not built at all; verify/verify.sh checks the
# list against probe.go.
readonly DEMUXERS="matroska,mov,mpegts,mpegps,mpegvideo,avi,flv,live_flv,ogg,asf,mxf,rm,\
flac,mp3,wav,aiff,wv,ape,dsf,iff,aac,ac3,eac3,dts,\
gif,image_png_pipe,image_jpeg_pipe,image_tiff_pipe,image_webp_pipe,\
srt,webvtt,ass,sup,image2"
# Output: fMP4 HLS (ADR 0024) selects mov, mpegts and webvtt itself; null serves diagnostics.
readonly MUXERS="hls,mp4,null"
# Encoders: the software transcode targets of ADR 0023.
readonly ENCODERS="libx264,aac"
# Filters: the graph endpoints and those ffmpeg inserts itself (pixel/sample format conversion,
# -t/-ss trimming, display-matrix rotation, crop metadata, -r, -apad, -vol), plus the producer's
# scale. Decoders, parsers and bitstream filters stay complete: the server plays any format.
readonly FILTERS="buffer,buffersink,abuffer,abuffersink,format,aformat,null,anull,\
scale,aresample,trim,atrim,crop,hflip,vflip,transpose,rotate,setpts,asetpts,fps,pad,setsar,\
apad,volume"
# The server opens every input as file: and writes HLS to files; pipe serves diagnostics.
readonly PROTOCOLS="file,pipe"

configure_ffmpeg() {
	PKG_CONFIG_LIBDIR="$prefix/lib/pkgconfig" PKG_CONFIG_PATH="" ./configure \
		--prefix="$prefix" --extra-version="static$RECIPE_REVISION" \
		--enable-cross-compile --target-os=linux --arch="$FFMPEG_ARCH" --cpu="$FFMPEG_CPU" \
		--cross-prefix="$TRIPLET-" --pkg-config=pkg-config --pkg-config-flags=--static \
		--extra-cflags="$ARCH_CFLAGS $HARDENING_CFLAGS -I$prefix/include" \
		--extra-ldflags="-L$prefix/lib $STATIC_LDFLAGS" \
		--enable-gpl --enable-version3 --enable-static --disable-shared \
		--disable-autodetect --enable-zlib --enable-iconv --enable-libx264 --enable-libdav1d \
		--disable-debug --disable-doc --disable-ffplay --disable-avdevice --disable-network \
		--disable-protocols --enable-protocol="$PROTOCOLS" \
		--disable-demuxers --enable-demuxer="$DEMUXERS" \
		--disable-muxers --enable-muxer="$MUXERS" \
		--disable-encoders --enable-encoder="$ENCODERS" \
		--disable-filters --enable-filter="$FILTERS"
}

# check_configuration refuses non-free parts and confirms the GPLv3 licence.
check_configuration() {
	configuration=$(sed -n 's/^#define FFMPEG_CONFIGURATION "\(.*\)"$/\1/p' config.h)
	licence=$(sed -n 's/^#define FFMPEG_LICENSE "\(.*\)"$/\1/p' config.h)
	case "$configuration" in
	*nonfree* | *fdk*) fail "the configuration contains non-free parts: $configuration" ;;
	esac
	case "$licence" in
	"GPL version 3 or later") ;;
	*) fail "unexpected licence '$licence'" ;;
	esac
	printf '%s\n' "$configuration" >"$dest/configuration.txt"
}

fail() {
	printf 'build-ffmpeg.sh: %s\n' "$*" >&2
	exit 1
}

mkdir -p "$work" "$dest"
tar -xJf "$sources/$FFMPEG_FILE" -C "$work" --strip-components=1
cd "$work"
if ! configure_ffmpeg >configure.out 2>&1; then
	tail -n 40 ffbuild/config.log >&2
	fail "configure failed"
fi
check_configuration
make -j"$jobs" ffmpeg ffprobe >make.out 2>&1 || {
	tail -n 60 make.out >&2
	fail "make failed"
}
"$TRIPLET-strip" -o "$dest/ffmpeg" ffmpeg_g
"$TRIPLET-strip" -o "$dest/ffprobe" ffprobe_g
mkdir -p "$LICENSE_DIR"
cp COPYING.GPLv3 LICENSE.md "$LICENSE_DIR/"
cd /
rm -rf "$work"
printf 'build-ffmpeg.sh: FFmpeg %s for %s in %s\n' "$(version_label "$FFMPEG_VERSION")" "$family" "$dest"
