#!/bin/sh
# build-libs.sh - build the static libraries FFmpeg links for one family: zlib, x264, dav1d.
#
#   build-libs.sh <family> <libs-sources> <prefix>
#
# <libs-sources> holds the verified tarballs and versions.env of the "libs" stage. The cross
# toolchain must be on PATH. Headers, static libraries and pkg-config files go to <prefix>.
#
# Why these libraries: zlib for the PNG decoder and compressed Matroska/MP4 headers, x264 for
# the H.264 transcode target (ADR 0023), dav1d because FFmpeg's own AV1 decoder only works with
# a hardware decoder. Each is reduced to what FFmpeg uses (README.md "Configuration").
#
# Environment: JOBS (parallel make jobs, default: number of CPUs).
# shellcheck source-path=SCRIPTDIR
set -eu

[ "$#" -eq 3 ] || {
	printf 'usage: %s <family> <libs-sources> <prefix>\n' "$0" >&2
	exit 2
}
family=$1
sources=$2
prefix=$3
script_dir=$(dirname "$0")

# shellcheck source=families.sh
. "$script_dir/families.sh"
# shellcheck source=layout.sh
. "$script_dir/layout.sh"
# shellcheck source=compile-flags.sh
. "$script_dir/compile-flags.sh"
load_family "$family"
# shellcheck disable=SC1091 # generated by fetch-sources.sh verify
. "$sources/versions.env"

jobs=${JOBS:-$(nproc)}
work="$BUILD_ROOT/libs"
cflags="$ARCH_CFLAGS $HARDENING_CFLAGS"

unpack() {
	mkdir -p "$work/$1"
	tar -xf "$sources/$2" -C "$work/$1" --strip-components=1
}

# keep_licence copies a licence text of a component into LICENSE_DIR as <component>-<file>.
keep_licence() {
	mkdir -p "$LICENSE_DIR"
	cp "$work/$1/$2" "$LICENSE_DIR/$1-$2"
}

build_zlib() {
	unpack zlib "$ZLIB_FILE"
	(
		cd "$work/zlib"
		CHOST=$TRIPLET CC="$TRIPLET-gcc" AR="$TRIPLET-ar" RANLIB="$TRIPLET-ranlib" CFLAGS="$cflags -O2" \
			./configure --static --prefix="$prefix"
		make -j"$jobs" install
	)
}

# x264: 8-bit 4:2:0 only, the transcode target of ADR 0023; no command-line tool. Its own
# config.sub predates the musl triplets, and x264 only needs "<cpu>-linux" from the host.
build_x264() {
	unpack x264 "$X264_FILE"
	(
		cd "$work/x264"
		./configure --host="${TRIPLET%%-*}-linux" --cross-prefix="$TRIPLET-" --prefix="$prefix" \
			--enable-static --disable-cli --disable-opencl --bit-depth=8 --chroma-format=420 \
			--extra-cflags="$cflags"
		make -j"$jobs"
		make install-lib-static
	)
}

# meson_list turns blank-separated flags into a meson array literal.
meson_list() {
	list=""
	for flag in "$@"; do list="$list${list:+, }'$flag'"; done
	printf '[%s]' "$list"
}

write_meson_cross_file() {
	# shellcheck disable=SC2086 # split the flag strings into array elements
	c_args=$(meson_list $cflags)
	# shellcheck disable=SC2086
	link_args=$(meson_list $STATIC_LDFLAGS)
	cat >"$1" <<EOF
[binaries]
c = '$TRIPLET-gcc'
ar = '$TRIPLET-ar'
strip = '$TRIPLET-strip'
nasm = 'nasm'

[built-in options]
c_args = $c_args
c_link_args = $link_args

[host_machine]
system = 'linux'
cpu_family = '$MESON_CPU_FAMILY'
cpu = '$MESON_CPU'
endian = 'little'
EOF
}

build_dav1d() {
	unpack dav1d "$DAV1D_FILE"
	write_meson_cross_file "$work/dav1d-cross.txt"
	meson setup "$work/dav1d/build" "$work/dav1d" --cross-file "$work/dav1d-cross.txt" \
		--prefix="$prefix" --libdir=lib --buildtype=release -Ddefault_library=static \
		-Denable_tools=false -Denable_tests=false -Denable_examples=false -Denable_docs=false
	ninja -C "$work/dav1d/build" -j "$jobs" install
	# Record whether the assembly (with run-time CPU detection) was built.
	grep -E '^#define (ARCH_[A-Z0-9_]+|HAVE_ASM) 1' "$work/dav1d/build/config.h" >&2 || true
}

build_zlib
build_x264
build_dav1d
keep_licence zlib LICENSE
keep_licence x264 COPYING
keep_licence dav1d COPYING
rm -rf "$work"
printf 'build-libs.sh: zlib %s, x264 %s, dav1d %s for %s in %s\n' \
	"$ZLIB_VERSION" "$X264_VERSION" "$DAV1D_VERSION" "$family" "$prefix"
