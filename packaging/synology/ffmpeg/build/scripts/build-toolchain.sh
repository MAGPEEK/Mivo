#!/bin/sh
# build-toolchain.sh - build the musl cross toolchain of one family with musl-cross-make.
#
#   build-toolchain.sh <family> <toolchain-sources> <output>
#
# <toolchain-sources> holds the verified tarballs and versions.env of the "toolchain" stage
# (fetch-sources.sh verify). musl-cross-make treats a SOURCES directory outside its tree as
# read-only and downloads nothing, so only the pinned tarballs are used; its own patches
# (part of the pinned musl-cross-make tarball) are applied to gcc, binutils and musl.
# The toolchain is installed to <output> (<output>/bin/<triplet>-gcc etc.); the licences of
# musl and libgcc, which end up in every binary, go to LICENSE_DIR.
#
# Environment: JOBS (parallel make jobs, default: number of CPUs).
# shellcheck source-path=SCRIPTDIR
set -eu

[ "$#" -eq 3 ] || {
	printf 'usage: %s <family> <toolchain-sources> <output>\n' "$0" >&2
	exit 2
}
family=$1
sources=$2
output=$3
script_dir=$(dirname "$0")

# shellcheck source=families.sh
. "$script_dir/families.sh"
# shellcheck source=layout.sh
. "$script_dir/layout.sh"
load_family "$family"
# shellcheck disable=SC1091 # generated by fetch-sources.sh verify
. "$sources/versions.env"

jobs=${JOBS:-$(nproc)}
work="$BUILD_ROOT/musl-cross-make"

fail() {
	printf 'build-toolchain.sh: %s\n' "$*" >&2
	exit 1
}

for file in "$MUSL_CROSS_MAKE_FILE" "$BINUTILS_FILE" "$GCC_FILE" "$MUSL_FILE" "$GMP_FILE" "$MPC_FILE" "$MPFR_FILE"; do
	[ -f "$sources/$file" ] || fail "missing $file"
done

mkdir -p "$work"
tar -xzf "$sources/$MUSL_CROSS_MAKE_FILE" -C "$work" --strip-components=1

# LINUX_VER is empty: no kernel headers; the libraries and FFmpeg's reduced configure need none.
# GCC_TARGET_CONFIG makes the family baseline the compiler default, so musl and libgcc are
# built for it. --with-debug-prefix-map keeps build paths out of the target libraries.
cat >"$work/config.mak" <<EOF
TARGET = $TRIPLET
OUTPUT = $output
SOURCES = $sources
BINUTILS_VER = $BINUTILS_VERSION
GCC_VER = $GCC_VERSION
MUSL_VER = $MUSL_VERSION
GMP_VER = $GMP_VERSION
MPC_VER = $MPC_VERSION
MPFR_VER = $MPFR_VERSION
LINUX_VER =
COMMON_CONFIG += CFLAGS="-g0 -O2" CXXFLAGS="-g0 -O2" LDFLAGS="-s"
COMMON_CONFIG += --disable-nls
COMMON_CONFIG += --with-debug-prefix-map=\$(CURDIR)=
GCC_CONFIG += --enable-languages=c
GCC_CONFIG += --disable-libquadmath --disable-decimal-float --disable-libitm --disable-fixed-point
GCC_CONFIG += --disable-lto --disable-libgomp
GCC_CONFIG += $GCC_TARGET_CONFIG
EOF

if ! make -C "$work" -j"$jobs" install >"$work/build.log" 2>&1; then
	tail -n 80 "$work/build.log" >&2
	fail "musl-cross-make failed for $TRIPLET"
fi

mkdir -p "$LICENSE_DIR"
cp "$work/gcc-$GCC_VERSION/COPYING.RUNTIME" "$LICENSE_DIR/gcc-COPYING.RUNTIME"
cp "$work/gcc-$GCC_VERSION/COPYING3" "$LICENSE_DIR/gcc-COPYING3"
cp "$work/musl-$MUSL_VERSION/COPYRIGHT" "$LICENSE_DIR/musl-COPYRIGHT"

# Smoke test: the toolchain links a fully static program for the baseline.
probe=$(mktemp -d)
printf 'int main(void) { return 0; }\n' >"$probe/probe.c"
# shellcheck disable=SC2086 # ARCH_CFLAGS is a list of flags
"$output/bin/$TRIPLET-gcc" $ARCH_CFLAGS -static -o "$probe/probe" "$probe/probe.c"
if "$output/bin/$TRIPLET-readelf" -lW "$probe/probe" | grep -q INTERP; then
	fail "the probe program is not static"
fi
rm -rf "$probe" "$work"
printf 'build-toolchain.sh: %s toolchain (gcc %s, binutils %s, musl %s) in %s\n' \
	"$TRIPLET" "$GCC_VERSION" "$BINUTILS_VERSION" "$MUSL_VERSION" "$output"
