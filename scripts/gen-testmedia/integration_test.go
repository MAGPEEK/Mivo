const (
	// repositoryCorpus is the default output directory seen from this package directory.
	repositoryCorpus = "../../testdata/media"
	// durationTolerance allows for container and codec framing around the nominal length.
	durationTolerance = 0.25
	// chapterTolerance allows for the time base conversion of chapter boundaries.
	chapterTolerance  = 0.01
	hdr10SideData     = "Mastering display metadata"
	contentLightLevel = "Content light level metadata"
)

// requireFFmpeg returns the paths of ffmpeg and ffprobe or skips the test.
func requireFFmpeg(t *testing.T) (ffmpegPath, ffprobePath string) {
	t.Helper()

	ffmpegPath, ffmpegErr := exec.LookPath("ffmpeg")
	ffprobePath, ffprobeErr := exec.LookPath("ffprobe")

	if ffmpegErr != nil || ffprobeErr != nil {
		t.Skip("skipping FFmpeg integration test: ffmpeg and ffprobe must be on PATH " +
			"(install FFmpeg, see docs/adr/0021-generated-test-media-corpus.md)")
	}

	return ffmpegPath, ffprobePath
}

// generateCases runs the program once per case name into outDir and returns the manifest.
func generateCases(t *testing.T, ffmpegPath, outDir string, names ...string) manifest {
	t.Helper()

	for _, name := range names {
		args := []string{"-out", outDir, "-ffmpeg", ffmpegPath, "-only", name, "-jobs", "1"}

		var stdout, stderr bytes.Buffer
		if code := run(context.Background(), args, &stdout, &stderr); code != exitOK {
			t.Fatalf("%s: exit code %d\nstdout:\n%s\nstderr:\n%s", name, code, stdout.String(), stderr.String())
		}
	}

	return readManifest(t, outDir)
}

func TestIntegrationGeneratesMKVCase(t *testing.T) {
	ffmpegPath, ffprobePath := requireFFmpeg(t)
	t.Parallel()

	outDir := t.TempDir()
	entry := manifestEntryByName(t, generateCases(t, ffmpegPath, outDir, "video-mkv-h264-aac"), "video-mkv-h264-aac")

	if entry.Status != statusGenerated {
		t.Fatalf("entry = %+v", entry)
	}

	verifyEntry(t, ffprobePath, outDir, entry)

	// A second run keeps the file instead of encoding it again.
	path := filepath.Join(outDir, filepath.FromSlash(entry.File))
	before := modificationTime(t, path)

	generateCases(t, ffmpegPath, outDir, "video-mkv-h264-aac")

	if after := modificationTime(t, path); !after.Equal(before) {
		t.Errorf("existing file was rewritten without -force (%v -> %v)", before, after)
	}
}

// TestIntegrationGeneratesMultiTrackCase checks streams, languages and dispositions of the
// multi-track case directly in ffprobe's JSON, independent of the manifest expectation.
func TestIntegrationGeneratesMultiTrackCase(t *testing.T) {
	ffmpegPath, ffprobePath := requireFFmpeg(t)
	t.Parallel()

	const name = "multitrack-mkv-eng-deu"

	outDir := t.TempDir()
	entry := manifestEntryByName(t, generateCases(t, ffmpegPath, outDir, name), name)

	result := probeFile(t, ffprobePath, filepath.Join(outDir, filepath.FromSlash(entry.File)))

	want := []string{
		"video h264 lang= default=0 forced=0",
		"audio aac lang=eng default=1 forced=0",
		"audio aac lang=deu default=0 forced=0",
		"subtitle subrip lang=eng default=0 forced=0",
		"subtitle subrip lang=deu default=0 forced=1",
	}

	got := make([]string, 0, len(result.Streams))
	for _, stream := range result.Streams {
		got = append(got, fmt.Sprintf("%s %s lang=%s default=%d forced=%d", stream.CodecType, stream.CodecName,
			stream.Tags.Language, stream.Disposition.Default, stream.Disposition.Forced))
	}

	if !slices.Equal(got, want) {
		t.Errorf("streams =\n%q\nwant\n%q", got, want)
	}

	verifyEntry(t, ffprobePath, outDir, entry)
}

// TestIntegrationGeneratesNewCategories builds one representative case of every category
// M1-19 added and verifies it against its manifest expectation.
func TestIntegrationGeneratesNewCategories(t *testing.T) {
	ffmpegPath, ffprobePath := requireFFmpeg(t)
	t.Parallel()

	names := []string{
		"audio-flac-24bit-96k", "audio-m4b-aac-chapters", "image-png", "image-gif-animated", "image-avif",
		"subtitle-sidecar-srt-vtt-ass", "subtitle-mkv-srt-ass", "subtitle-mp4-movtext",
	}

	outDir := t.TempDir()
	result := generateCases(t, ffmpegPath, outDir, names...)

	for _, name := range names {
		entry := manifestEntryByName(t, result, name)

		t.Run(name, func(t *testing.T) {
			if entry.Status != statusGenerated {
				t.Skipf("not generated by the local FFmpeg: %s", entry.Reason)
			}

			verifyEntry(t, ffprobePath, outDir, entry)
		})
	}
}

// TestIntegrationCorpusMatchesManifest verifies every generated file of the repository corpus
// (`go run ./scripts/gen-testmedia`) with ffprobe against its expected properties.
func TestIntegrationCorpusMatchesManifest(t *testing.T) {
	_, ffprobePath := requireFFmpeg(t)
	t.Parallel()

	data, err := fs.ReadFile(os.DirFS(repositoryCorpus), manifestFileName)
	if err != nil {
		t.Skipf("skipping corpus check: no corpus at %s (run `go run ./scripts/gen-testmedia`)", repositoryCorpus)
	}

	// Older manifests have another shape; read the version before decoding the cases.
	var version struct {
		SchemaVersion int `json:"schemaVersion"`
	}
	if err := json.Unmarshal(data, &version); err != nil || version.SchemaVersion != manifestSchemaVersion {
		t.Skipf("skipping corpus check: manifest schema %d is not %d (run `go run ./scripts/gen-testmedia`)",
			version.SchemaVersion, manifestSchemaVersion)
	}

	for _, entry := range readManifest(t, repositoryCorpus).Cases {
		if entry.Status != statusGenerated {
			continue
		}

		t.Run(entry.Name, func(t *testing.T) {
			t.Parallel()
			verifyEntry(t, ffprobePath, repositoryCorpus, entry)
		})
	}
}

func manifestEntryByName(t *testing.T, result manifest, name string) manifestEntry {
	t.Helper()

	index := slices.IndexFunc(result.Cases, func(entry manifestEntry) bool { return entry.Name == name })
	if index < 0 {
		t.Fatalf("manifest has no entry %q", name)
	}

	return result.Cases[index]
}

func modificationTime(t *testing.T, path string) time.Time {
	t.Helper()

	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat %s: %v", path, err)
	}

	return info.ModTime()
}

// probeResult is the subset of `ffprobe -print_format json -show_format -show_streams
// -show_chapters`.
type probeResult struct {
	Format struct {
		FormatName string            `json:"format_name"`
		Duration   string            `json:"duration"`
		Tags       map[string]string `json:"tags"`
	} `json:"format"`
	Streams  []probeStream  `json:"streams"`
	Chapters []probeChapter `json:"chapters"`
}

type probeStream struct {
	CodecType        string `json:"codec_type"`
	CodecName        string `json:"codec_name"`
	Profile          string `json:"profile"`
	CodecTagString   string `json:"codec_tag_string"`
	PixelFormat      string `json:"pix_fmt"`
	ColorPrimaries   string `json:"color_primaries"`
	ColorTransfer    string `json:"color_transfer"`
	ColorSpace       string `json:"color_space"`
	Width            int    `json:"width"`
	Height           int    `json:"height"`
	SampleRate       string `json:"sample_rate"`
	Channels         int    `json:"channels"`
	BitsPerRawSample string `json:"bits_per_raw_sample"`
	Tags             struct {
		Language string `json:"language"`
	} `json:"tags"`
	Disposition struct {
		Default int `json:"default"`
		Forced  int `json:"forced"`
	} `json:"disposition"`
}

type probeChapter struct {
	StartTime string `json:"start_time"`
	EndTime   string `json:"end_time"`
	Tags      struct {
		Title string `json:"title"`
	} `json:"tags"`
}

func runFFprobe(t *testing.T, ffprobePath string, args ...string) []byte {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), capabilityTimeout)
	defer cancel()

	output, err := execRunner{executable: ffprobePath}.Run(ctx, append([]string{"-v", "error"}, args...))
	if err != nil {
		t.Fatalf("ffprobe %v: %v", args, err)
	}

	return output
}

func probeFile(t *testing.T, ffprobePath, path string) probeResult {
	t.Helper()

	output := runFFprobe(t, ffprobePath, "-print_format", "json",
		"-show_format", "-show_streams", "-show_chapters", path)

	var result probeResult
	if err := json.Unmarshal(output, &result); err != nil {
		t.Fatalf("decode ffprobe output for %s: %v", path, err)
	}

	return result
}

// verifyEntry checks a generated file against the expected properties of its entry.
func verifyEntry(t *testing.T, ffprobePath, dir string, entry manifestEntry) {
	t.Helper()

	path := filepath.Join(dir, filepath.FromSlash(entry.File))
	if _, err := fs.Stat(os.DirFS(dir), entry.File); err != nil {
		t.Fatalf("generated file missing: %v", err)
	}

	result := probeFile(t, ffprobePath, path)
	expected := entry.Expected

	check(t, "format", result.Format.FormatName, expected.ProbeFormat)

	if expected.DurationSeconds > 0 {
		checkDuration(t, result.Format.Duration, expected.DurationSeconds)
	}

	if expected.Video != nil {
		videos := streamsOfType(result, "video")
		if len(videos) != 1 {
			t.Fatalf("%d video streams, want 1", len(videos))
		}

		verifyVideo(t, videos[0], *expected.Video)

		if expected.Video.HDR == "hdr10" {
			verifyHDR10SideData(t, ffprobePath, path)
		}
	}

	verifyAudio(t, streamsOfType(result, "audio"), expected.Audio)
	verifySubtitles(t, streamsOfType(result, "subtitle"), expected.Subtitles)
	verifyChapters(t, result.Chapters, expected.Chapters)

	for key, want := range expected.Tags {
		check(t, "tag "+key, result.Format.Tags[key], want)
	}

	verifySidecars(t, ffprobePath, dir, expected.Sidecars)
}

func verifyVideo(t *testing.T, stream probeStream, want videoExpectation) {
	t.Helper()

	check(t, "video codec", stream.CodecName, want.Codec)
	checkOptional(t, "video profile", stream.Profile, want.Profile)
	checkOptional(t, "codec tag", stream.CodecTagString, want.CodecTag)
	checkOptional(t, "pixel format", stream.PixelFormat, want.PixelFormat)
	checkOptional(t, "color primaries", stream.ColorPrimaries, want.ColorPrimaries)
	checkOptional(t, "color transfer", stream.ColorTransfer, want.ColorTransfer)
	checkOptional(t, "color space", stream.ColorSpace, want.ColorSpace)
	check(t, "size", fmt.Sprintf("%dx%d", stream.Width, stream.Height), fmt.Sprintf("%dx%d", want.Width, want.Height))
}

func verifyAudio(t *testing.T, streams []probeStream, want []audioExpectation) {
	t.Helper()

	if len(streams) != len(want) {
		t.Fatalf("%d audio streams, want %d", len(streams), len(want))
	}

	for index, stream := range streams {
		check(t, "audio codec", stream.CodecName, want[index].Codec)
		check(t, "sample rate", stream.SampleRate, strconv.Itoa(want[index].SampleRate))
		check(t, "channels", strconv.Itoa(stream.Channels), strconv.Itoa(want[index].Channels))

		if want[index].BitDepth > 0 {
			check(t, "bit depth", stream.BitsPerRawSample, strconv.Itoa(want[index].BitDepth))
		}

		verifyTrack(t, stream, want[index].Track)
	}
}

func verifySubtitles(t *testing.T, streams []probeStream, want []subtitleExpectation) {
	t.Helper()

	if len(streams) != len(want) {
		t.Fatalf("%d subtitle streams, want %d", len(streams), len(want))
	}

	for index, stream := range streams {
		check(t, "subtitle codec", stream.CodecName, want[index].Codec)
		verifyTrack(t, stream, want[index].Track)
	}
}

func verifyTrack(t *testing.T, stream probeStream, want *trackExpectation) {
	t.Helper()

	if want == nil {
		return
	}

	check(t, stream.CodecType+" language", stream.Tags.Language, want.Language)
	check(t, stream.CodecType+" default", strconv.Itoa(stream.Disposition.Default), strconv.Itoa(boolToInt(want.Default)))
	check(t, stream.CodecType+" forced", strconv.Itoa(stream.Disposition.Forced), strconv.Itoa(boolToInt(want.Forced)))
}

func verifyChapters(t *testing.T, chapters []probeChapter, want []chapterExpectation) {
	t.Helper()

	if len(chapters) != len(want) {
		t.Fatalf("%d chapters, want %d", len(chapters), len(want))
	}

	for index, chapter := range chapters {
		check(t, "chapter title", chapter.Tags.Title, want[index].Title)
		checkChapterTime(t, "chapter start", chapter.StartTime, want[index].StartSeconds)
		checkChapterTime(t, "chapter end", chapter.EndTime, want[index].EndSeconds)
	}
}

// verifySidecars checks that FFmpeg reads every sidecar as the expected subtitle format.
func verifySidecars(t *testing.T, ffprobePath, dir string, sidecars []sidecarExpectation) {
	t.Helper()

	for _, sidecar := range sidecars {
		result := probeFile(t, ffprobePath, filepath.Join(dir, filepath.FromSlash(sidecar.File)))

		check(t, sidecar.File+" format", result.Format.FormatName, sidecar.ProbeFormat)

		streams := streamsOfType(result, "subtitle")
		if len(streams) != 1 {
			t.Errorf("%s: %d subtitle streams, want 1", sidecar.File, len(streams))

			continue
		}

		check(t, sidecar.File+" codec", streams[0].CodecName, sidecar.Codec)
	}
}

// verifyHDR10SideData checks the first frame for HDR10 mastering display and light level SEI.
func verifyHDR10SideData(t *testing.T, ffprobePath, path string) {
	t.Helper()

	output := runFFprobe(t, ffprobePath, "-select_streams", "v:0", "-read_intervals", "%+#1",
		"-show_frames", "-show_entries", "frame=side_data_list", "-print_format", "json", path)

	var frames struct {
		Frames []struct {
			SideData []struct {
				Type string `json:"side_data_type"`
			} `json:"side_data_list"`
		} `json:"frames"`
	}
	if err := json.Unmarshal(output, &frames); err != nil {
		t.Fatalf("decode frame side data: %v", err)
	}

	found := map[string]bool{}

	for _, frame := range frames.Frames {
		for _, sideData := range frame.SideData {
			found[sideData.Type] = true
		}
	}

	if !found[hdr10SideData] || !found[contentLightLevel] {
		t.Errorf("first frame lacks HDR10 side data, found %v", found)
	}
}

// streamsOfType returns the streams of one codec type in stream order.
func streamsOfType(result probeResult, codecType string) []probeStream {
	var streams []probeStream

	for _, stream := range result.Streams {
		if stream.CodecType == codecType {
			streams = append(streams, stream)
		}
	}

	return streams
}

// checkDuration compares an ffprobe duration with the nominal length of the case.
func checkDuration(t *testing.T, reported string, want float64) {
	t.Helper()
	checkWithin(t, "duration", parseSeconds(t, reported)-want, durationTolerance)
}

// checkChapterTime compares an ffprobe chapter boundary with the expected one.
func checkChapterTime(t *testing.T, property, reported string, want float64) {
	t.Helper()
	checkWithin(t, property, parseSeconds(t, reported)-want, chapterTolerance)
}

func parseSeconds(t *testing.T, reported string) float64 {
	t.Helper()

	seconds, err := strconv.ParseFloat(reported, 64)
	if err != nil {
		t.Fatalf("time %q is not a number", reported)
	}

	return seconds
}

func checkWithin(t *testing.T, property string, difference, tolerance float64) {
	t.Helper()

	if math.Abs(difference) > tolerance {
		t.Errorf("%s is off by %.3f s, tolerance %.2f s", property, difference, tolerance)
	}
}

func check(t *testing.T, property, got, want string) {
	t.Helper()

	if got != want {
		t.Errorf("%s = %q, want %q", property, got, want)
	}
}

func checkOptional(t *testing.T, property, got, want string) {
	t.Helper()

	if want != "" {
		check(t, property, got, want)
	}
}

func boolToInt(value bool) int {
	if value {
		return 1
	}

	return 0
}
